import { readFileSync } from "node:fs";
import { decodePng } from "./lib/raster.mjs";
import { analyseDeck } from "../src/convex/lib/visual";
import { RULES, PALETTE } from "../src/convex/lib/lumora";
const fx = JSON.parse(readFileSync("eval/visual-fixtures.json","utf8"));
const vr = RULES.filter(r=>r.ruleId.startsWith("VIS-"));
const deck = fx.decks[0];
const pages = deck.pages.map(p=>({page:p.page,image:decodePng(readFileSync(p.png)),text:p.textItems}));
const r = analyseDeck({pages,rules:vr,palette:PALETTE.map(p=>p.hex)});
console.log(JSON.stringify(r.findings.slice(0,2),null,1));
const v = fx.decks[1];
const vp = v.pages.map(p=>({page:p.page,image:decodePng(readFileSync(p.png)),text:p.textItems}));
const rv = analyseDeck({pages:vp,rules:vr,palette:PALETTE.map(p=>p.hex)});
console.log("p3", JSON.stringify(rv.findings.filter(f=>f.page===3 && f.ruleId.includes("CLEAR")),null,1));
console.log("truth", JSON.stringify(v.groundTruth.violations.filter((x:any)=>x.page===3)));
